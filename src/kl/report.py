"""Writes FEATURES.md and METHODS.md from the JSON results produced by the pipeline scripts.

METHODS.md is regenerated from whatever results exist; sections whose step has not run yet say so
explicitly instead of inventing numbers.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from .config import Settings, read_json
from .features import BOUNDED_RATE_FEATURES, FEATURE_SPECS, compute_features, worked_example

NOT_RUN = "[not yet computed: run the corresponding step]"
REVISION1_ARCHIVE = Path("docs") / "revision1_original_rule_diagnostics.json"


def write_features_md(path: Path) -> None:
    """Generate FEATURES.md (name, group, formula, unit, model transform, value on the worked example)."""
    ex = worked_example()
    vals = compute_features(ex)
    lines = [
        "# Features", "",
        "Auto-generated by `kl.report.write_features_md`. One code path (`kl.features`) is used for human "
        "and bot sessions. Keys are identified by KEYCODE (Backspace 8, Delete 46, Shift 16); LETTER is never used.", "",
        "Model input transform (`kl.model.FeatureTransform`): bounded rates in [0, 1] "
        f"({', '.join('`%s`' % n for n in sorted(BOUNDED_RATE_FEATURES))}) are used as they are; every other feature is passed through the "
        "signed log `y = sign(x) * log1p(|x|)`; then a RobustScaler (median / IQR) fitted on the TRAIN split only.", "",
        "Revision 1 (2026-09-24): `flight_cv` was removed (undefined when the mean flight is ~0 because of rollover; it reached ~7e7 on the "
        "train split); `flight_median` and `flight_iqr` were added.", "",
        "Worked example (3 keys, SENTENCE=`abc`, USER_INPUT=`abd`):", "",
        "| key | PRESS | RELEASE | KEYCODE |", "|---|---|---|---|",
    ]
    for _, r in ex.iterrows():
        lines.append(f"| {r['LETTER']} | {r['PRESS_TIME']:.0f} | {r['RELEASE_TIME']:.0f} | {r['KEYCODE']} |")
    lines += [
        "", "hold = [100, 80, 110], pp = [200, 250], rr = [180, 280], flight = [100, 170] (ms). "
        "Standard deviations are population standard deviations (ddof = 0).", "",
        "| name | group | formula | unit | model transform | worked example |", "|---|---|---|---|---|---|",
    ]
    for s in FEATURE_SPECS:
        tf = "none (bounded) + robust scale" if s.name in BOUNDED_RATE_FEATURES else "signed log + robust scale"
        lines.append(f"| `{s.name}` | {s.group} | {s.formula} | {s.unit} | {tf} | {vals[s.name]:.4g} |")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def _g(d: Any, dotted: str, default: Any = None) -> Any:
    """Nested dict lookup with a dotted path."""
    cur = d
    for part in dotted.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return default
        cur = cur[part]
    return cur


def _n(x: Any) -> str:
    return NOT_RUN if x is None else f"{int(x):,}"


def _pct(x: Any, digits: int = 2) -> str:
    return NOT_RUN if x is None else f"{100 * float(x):.{digits}f}%"


def _f(x: Any, digits: int = 3) -> str:
    return NOT_RUN if x is None else f"{float(x):.{digits}f}"


def write_methods_md(settings: Settings, path: Path | None = None) -> Path:
    """(Re)generate METHODS.md from the JSON results under ``settings.results_dir``."""
    res = settings.results_dir
    cfg = settings.cfg
    clean = read_json(res / "cleaning_report.json", {}) or {}
    s1, s2 = clean.get("step1_sampling"), clean.get("step2_cleaning")
    man = read_json(res / "split_manifest.json")
    feat = read_json(res / "features_report.json")
    sel = read_json(res / "selection.json")
    stopped = read_json(res / "selection_stopped.json")
    test = read_json(res / "test_results.json")
    a1 = read_json(res / "a1_results.json")
    orig = read_json(settings.root / REVISION1_ARCHIVE)
    a1c, scfg = cfg["a1"], cfg["selection"]
    adm = scfg["admissibility"]
    incl = ", ".join(_g(s1, "keyboard_types_include", cfg["sampling"]["keyboard_types_include"]))
    tol_pp = 100 * scfg["tie_tolerance"]

    kt = _g(s1, "keyboard_type_counts", {}) or {}
    kt_txt = ", ".join(f"{k}: {v:,}" for k, v in kt.items()) or NOT_RUN
    cnt = _g(man, "counts.sessions", {}) or {}
    ucnt = _g(man, "counts.users", {}) or {}
    grid_path = res / "grid_results.csv"
    grid = pd.read_csv(grid_path) if grid_path.exists() else None

    p: list[str] = ["# Methods", "", f"_Run mode: **{'quick' if settings.quick else 'full'}**, seed {settings.seed}, config hash `{settings.config_hash}`. "
                    "Protocol: docs/PHASE1_SPEC.md incl. Revision 1._", ""]
    p += ["## Paper-ready paragraph", ""]

    # --- data
    p.append(
        f"**Data.** We used the Aalto 136M Keystrokes dataset (Dhakal et al., CHI 2018), in which each participant typed "
        f"up to 15 sentences in an online typing test. The metadata file lists {_n(_g(s1, 'metadata_participants'))} participants "
        f"(KEYBOARD_TYPE counts — {kt_txt}). We kept only participants who typed on a physical keyboard "
        f"(KEYBOARD_TYPE ∈ {{{incl}}}), excluding small-physical and on-screen (touch) keyboards and any missing or unmapped value, "
        f"which leaves {_n(_g(s1, 'eligible'))} eligible participants, {_n(_g(s1, 'eligible_with_file'))} of which have a keystroke file. "
        f"From these we drew {_n(_g(s1, 'sampled'))} participants uniformly at random (seed {settings.seed}); "
        f"{_n(_g(s1, 'files_failed'))} sampled files could not be parsed and {_n(_g(s1, 'rows_read'))} keystroke rows were read."
    )
    p.append("")
    # --- sessions
    p.append(
        f"**Sessions and cleaning.** A session is one typed sentence (PARTICIPANT_ID, TEST_SECTION_ID). Of {_n(_g(s2, 'sessions_total'))} sessions, "
        f"{_n(_g(s2, 'dropped_total'))} were dropped ({_n(_g(s2, 'drop_too_few_keystrokes'))} with fewer than {cfg['cleaning']['min_keystrokes']} keystrokes; "
        f"{_n(_g(s2, 'drop_bad_times'))} with missing/non-numeric times; {_n(_g(s2, 'drop_hold_out_of_range'))} with a hold < {cfg['cleaning']['min_hold_ms']:g} or > {cfg['cleaning']['max_hold_ms']:g} ms; "
        f"{_n(_g(s2, 'drop_gap_too_long'))} with a press-to-press gap > {cfg['cleaning']['max_press_gap_ms']:g} ms; "
        f"{_n(_g(s2, 'drop_empty_text'))} with empty SENTENCE or USER_INPUT; rules are counted independently, so one session can hit several), "
        f"leaving {_n(_g(s2, 'sessions_kept'))} clean sessions."
    )
    p.append("")
    # --- split
    fr = cfg["split"]["fractions"]
    p.append(
        f"**Split.** Users were split at the user level into train/validation/test/attacker-pool "
        f"({fr['train']:.0%}/{fr['val']:.0%}/{fr['test']:.0%}/{fr['attacker_pool']:.0%}): "
        f"{_n(ucnt.get('train'))}/{_n(ucnt.get('val'))}/{_n(ucnt.get('test'))}/{_n(ucnt.get('attacker_pool'))} users and "
        f"{_n(cnt.get('train'))}/{_n(cnt.get('val'))}/{_n(cnt.get('test'))}/{_n(cnt.get('attacker_pool'))} sessions "
        f"(train capped at {_n(_g(man, 'max_train_sessions'))} sessions from {_n(_g(man, 'counts.train_sessions_before_cap'))} by seeded uniform sampling). "
        f"The attacker pool is never used for training or tuning."
    )
    p.append("")
    # --- features + model + selection
    gr = f"ν ∈ {{{', '.join(str(v) for v in cfg['model']['nu_grid'])}}}, γ ∈ {{{', '.join(str(v) for v in cfg['model']['gamma_grid'])}}}"
    bounded = ", ".join(sorted(BOUNDED_RATE_FEATURES))
    if sel and _g(sel, "ref_accept_spread_tau5") is not None:
        spread_txt = (f"observed spread {100 * float(sel['ref_accept_spread_tau5']):.1f} pp, "
                      f"from {_pct(sel.get('min_ref_accept_tau5'), 1)} to {_pct(sel.get('max_ref_accept_tau5'), 1)}")
    elif stopped:
        spread_txt = f"reference acceptance {_pct(stopped.get('min_ref_accept_tau5'), 2)}–{_pct(stopped.get('max_ref_accept_tau5'), 2)} — SELECTION STOPPED"
    else:
        spread_txt = NOT_RUN
    p.append(
        f"**Model.** Each session is summarised by {_n(_g(sel, 'n_features', _g(feat, 'n_features')))} timing, rhythm, behaviour and global features "
        f"(FEATURES.md). Bounded rates ({bounded}) are used as they are; every other feature is passed through the signed logarithm "
        f"y = sign(x)·log(1 + |x|), and all features are then scaled with a RobustScaler (median / IQR) fitted on the training split only. "
        f"The transformed features feed an RBF One-Class SVM trained on human sessions only. We searched {gr} ({_n(_g(sel, 'grid_size', len(grid) if grid is not None else None))} configurations). "
        f"Without any attack data, configurations were first screened for overfitting: a configuration is admissible iff |FNR_val,native − ν| ≤ max({adm['abs_tol']:g}, {adm['rel_tol']:g}·ν), "
        f"where FNR_val,native is the fraction of validation humans with a negative decision value (under the ν-property of the One-Class SVM, Schölkopf et al., 2001, ν approximates the held-out outlier fraction); "
        f"{_n(_g(sel, 'n_admissible'))} of {_n(_g(sel, 'grid_size'))} configurations were admissible. Among these, the configuration was chosen with a reference set of M = {_n(scfg['n_reference_points'])} points drawn from the product "
        f"of the marginals of the transformed training data — every feature is resampled independently, with replacement, from its own training column "
        f"(cf. the artificial-outlier construction of Hempstalk, Frank & Witten, 2008, ECML PKDD) — and we picked the configuration accepting the fewest reference points "
        f"at the 5%-FNR threshold (ties within {tol_pp:.1f} percentage points → smaller ν, then smaller γ). A guard stops the selection if reference acceptance "
        f"spans less than {100 * scfg['min_reference_spread']:.0f} pp across the grid ({spread_txt}) or if no configuration is admissible; the tolerance is never relaxed automatically. "
        f"Chosen: ν = {_f(_g(sel, 'chosen.nu'), 2)}, γ = {_g(sel, 'chosen.gamma', NOT_RUN)} (effective {_f(_g(sel, 'chosen.gamma_effective'), 4)}); "
        f"the decision threshold τ was set on the validation humans as the score quantile giving FNR = 5% (τ5 = {_f(_g(sel, 'chosen.tau5'), 4)}) "
        f"and 10% (τ10 = {_f(_g(sel, 'chosen.tau10'), 4)}). A session is accepted as human iff its score ≥ τ."
    )
    p.append("")
    # --- selection rule revision
    ud = _g(sel, "uniform_diagnostic") or (
        {"min_tau5": float(grid["uniform_accept_tau5"].min()), "max_tau5": float(grid["uniform_accept_tau5"].max()),
         "n_configs_zero_tau5": int((grid["uniform_accept_tau5"] == 0).sum())} if grid is not None and "uniform_accept_tau5" in grid else None)
    o = orig or {}
    p.append(
        f"**Selection rule revision.** The originally specified rule — uniform artificial outliers (Tax & Duin, 2001) drawn in the per-feature [min, max] box of the "
        f"standardised training data — was abandoned because it was degenerate. In the initial {o.get('run', 'quick-mode run')} ({o.get('n_features', 22)} features, "
        f"standard scaling), {_n(o.get('n_configs_zero_uniform_acceptance_tau5'))} of {_n(o.get('grid_size'))} configurations accepted none of the {_n(o.get('n_uniform_points'))} "
        f"uniform points at τ5, the most permissive accepted {_pct(o.get('max_uniform_acceptance_tau5'), 3)}, and {_n(o.get('n_configs_tied_within_tolerance'))} of {_n(o.get('grid_size'))} "
        f"configurations were tied within the {tol_pp:.1f} pp tolerance, so the tie-break alone chose the model (ν = {o.get('chosen', {}).get('nu', NOT_RUN)}, γ = {o.get('chosen', {}).get('gamma', NOT_RUN)}). "
        f"In {o.get('n_features', 22)} dimensions the volume of the box is dominated by heavy-tailed features — notably flight_cv, whose denominator vanishes when rollover makes the mean flight ≈ 0 "
        f"(train maximum ≈ {float(o.get('flight_cv_train_max', float('nan'))):.2g})" + f" — so uniformly drawn points almost never fall near the data and the criterion carries no information. "
        f"The revision (product-of-marginals reference set, signed-log + robust transform, flight_cv replaced by flight_median and flight_iqr) was motivated by this degeneracy of the selection "
        f"diagnostic, not by attack performance. The uniform-box acceptance is still computed as a diagnostic column (`uniform_accept_tau5` in grid_results.csv) and is never used for selection"
        + (f"; under the revised transform it ranges from {_pct(ud['min_tau5'], 3)} to {_pct(ud['max_tau5'], 3)} ({_n(ud['n_configs_zero_tau5'])} configurations at exactly 0%)." if ud else ".")
        + " Disclosure: the initial quick-mode test and A1 results had already been produced with the original rule before the revision was decided; the quick-mode test split was therefore "
        "evaluated twice (once under the original rule, once under the revised rule; `--allow-rerun`), whereas the revised protocol has not touched any full-scale test split before the freeze."
    )
    r1 = (o.get("revision1_selected_config_quick") or {})
    lo_sv, hi_sv = (r1.get("n_support_vectors_range_other_nu0.01_configs_gamma_le_0.03") or [None, None])
    p.append("")
    p.append(
        f"**Selection rule revision 2 (final).** With Revision 1 alone, the product-of-marginals criterion favoured the largest γ in the grid (γ = {r1.get('gamma', NOT_RUN)}): in the quick-mode run the selected "
        f"configuration (ν = {r1.get('nu', NOT_RUN)}) showed attack-free overfitting diagnostics — a validation FNR at the native decision boundary of {_pct(r1.get('val_fnr_native'), 1)} against ν = {_pct(r1.get('nu'), 0)}, "
        f"and {_n(r1.get('n_support_vectors'))} support vectors against {_n(lo_sv)}–{_n(hi_sv)} for the smoother ν = 0.01 configurations. The admissibility filter (|FNR_val,native − ν| ≤ max({adm['abs_tol']:g}, {adm['rel_tol']:g}·ν)) "
        f"was added on the basis of those diagnostics, which do not involve attack data. Disclosure: post-hoc A1 results had already been seen when this revision was made (in that run the Revision 1 configuration ranked "
        f"{_n(r1.get('posthoc_a1_rank_by_auc_seen_before_revision2'))} of 35 by A1 ROC-AUC in the post-hoc sensitivity table), so Revision 2 is not independent of them, although its trigger and its formula are attack-free. "
        f"Attacks A2–A5 (Phase 2) will be designed only after this freeze."
    )
    p.append("")
    p.append(
        "**Freeze.** Revision 2 is final: no further changes to the features, the input transform, the hyperparameter grid or the selection rule will be made in Phase 1, whatever the A1 results."
    )
    p.append("")
    # --- test
    t5, t10 = _g(test, "tau5", {}) or {}, _g(test, "tau10", {}) or {}
    ci = int(100 * cfg["evaluation"]["ci_level"])
    p.append(
        f"**Human test.** The test split (held out until selection was frozen) contains {_n(_g(test, 'n_sessions'))} sessions from "
        f"{_n(_g(test, 'n_users'))} users. The false-negative rate (humans rejected) is {_pct(t5.get('fnr'))} at τ5 "
        f"({ci}% user-level bootstrap CI {_pct(t5.get('ci_lo'))}–{_pct(t5.get('ci_hi'))}) and {_pct(t10.get('fnr'))} at τ10 "
        f"({_pct(t10.get('ci_lo'))}–{_pct(t10.get('ci_hi'))}; {cfg['evaluation']['bootstrap_reps']} resamples of users)."
    )
    p.append("")
    # --- A1
    a5, a10 = _g(a1, "tau5", {}) or {}, _g(a1, "tau10", {}) or {}
    p.append(
        f"**A1 sanity check.** After freezing the model we generated one bot session per test session ({_n(_g(a1, 'n_bot_sessions'))}) with a generator "
        f"that draws independent Gaussian holds N({a1c['hold_mean_ms']}, {a1c['hold_std_ms']}) ms (min {a1c['hold_min_ms']:g} ms) and flights "
        f"N({a1c['flight_mean_ms']}, {a1c['flight_std_ms']}) ms (min {a1c['flight_min_ms']:g} ms). Bots accepted as human (FPR): "
        f"{_pct(a5.get('FPR_bots_accepted'))} at τ5 and {_pct(a10.get('FPR_bots_accepted'))} at τ10; ROC-AUC = {_f(_g(a1, 'auc'), 4)}."
    )
    p.append("")
    gs = _g(a1, "grid_sensitivity")
    if gs:
        s_ = gs["selected"]
        p.append(
            f"**Post-hoc sensitivity (not used for selection).** A1 was also evaluated for all {gs['n_configs']} grid configurations, each with its own τ5/τ10 from the validation "
            f"humans (grid_attack_sensitivity.csv). The selected configuration ranks {int(s_['rank_by_auc'])} of {gs['n_configs']} by ROC-AUC ({_f(s_['auc'], 4)}; grid range "
            f"{_f(gs['auc_min'], 4)}–{_f(gs['auc_max'], 4)}, median {_f(gs['auc_median'], 4)}; best: ν = {gs['best_by_auc']['nu']}, γ = {gs['best_by_auc']['gamma']}, AUC {_f(gs['best_by_auc']['auc'], 4)}) "
            f"and {int(s_['rank_by_fpr_tau5'])} of {gs['n_configs']} by FPR at τ5 ({_pct(s_['fpr_tau5'])}; grid range {_pct(gs['fpr_tau5_min'])}–{_pct(gs['fpr_tau5_max'])}). "
            f"This table is post-hoc and was not used to choose the configuration."
        )
        p.append("")
    p += ["## Results at a glance", "",
          "| quantity | value |", "|---|---|",
          f"| FNR (humans rejected) @ τ5, test | {_pct(t5.get('fnr'))} |",
          f"| FNR (humans rejected) @ τ10, test | {_pct(t10.get('fnr'))} |",
          f"| FPR (bots accepted) @ τ5, A1 | {_pct(a5.get('FPR_bots_accepted'))} |",
          f"| FPR (bots accepted) @ τ10, A1 | {_pct(a10.get('FPR_bots_accepted'))} |",
          f"| ROC-AUC (human vs A1) | {_f(_g(a1, 'auc'), 4)} |", ""]
    p += ["## Assumptions and implementation choices", ""]
    assumptions = [
        f"**HOLD_MIN = {a1c['hold_min_ms']:g} ms (ASSUMPTION)** and FLIGHT_MIN = {a1c['flight_min_ms']:g} ms clamp the A1 draws; A1 times are rounded to integer ms.",
        "**A1 Shift handling is a reconstruction:** Shift-down → key-down delay is a flight draw; Shift is released HOLD_MIN ms after the key is released; the next character starts one flight after the Shift release. Unmapped characters get keycode 229.",
        "A1 keycodes: letters (either case) use the uppercase ASCII code, digits their ASCII code, space 32; punctuation follows the US-layout table in `kl/attacks/a1_gaussian.py`.",
        "Standard deviations are population standard deviations (ddof = 0); `flight_iqr` uses linearly interpolated percentiles (`np.percentile`).",
        "`correction_rate` = corrections_count / n_keys; `rollover_rate` = share of the n_keys − 1 intervals with flight < 0.",
        "`shift_overlap_count`: for each Shift hold, non-Shift keys with PRESS strictly inside (PRESS_shift, RELEASE_shift) minus one, floored at zero, summed over holds.",
        "Keys are identified by KEYCODE only; Enter (13) is never relied upon. Sessions are sorted by PRESS_TIME with KEYSTROKE_ID as tie-break only.",
        "Files are decoded as UTF-8 and fall back to latin-1 (the actual encoding of the corpus) when that fails; rows whose PARTICIPANT_ID differs from the file name are dropped and counted.",
        "The user split is drawn among participants that own at least one clean session (cleaning precedes splitting).",
        "Sessions with a non-finite feature (e.g. zero total duration) are dropped at the feature step and counted in features_report.json.",
        "τ is the empirical `np.quantile` of the validation scores at 5% / 10%; a session is rejected iff score < τ.",
        "Features with an IQR of zero on the train split (e.g. rarely non-zero counts) keep a scale of 1 in scikit-learn's RobustScaler.",
        "`gamma = \"scale\"` is resolved to its numeric value 1 / (n_features · Var(X_transformed_train)) before fitting; ties in the selection rule use this effective gamma.",
        "The reference set uses the transformed training sessions actually used to fit the SVM (after the session cap); the same reference points are used for every configuration. "
        "Reference acceptance is measured at the τ5 of each configuration.",
        f"Bootstrap: percentile CI over {cfg['evaluation']['bootstrap_reps']} resamples of test USERS (all their sessions), seeded.",
    ]
    if _g(a1, "notes"):
        assumptions += list(a1["notes"])
    p += [f"{i}. {a}" for i, a in enumerate(assumptions, 1)]

    diag: list[str] = []
    if sel:
        ud2 = sel.get("uniform_diagnostic", {})
        na = [f"ν={d['nu']:g}, γ={d['gamma']} (val FNR {100 * d['val_fnr_native']:.1f}%)" for d in (sel.get("not_admissible") or [])]
        diag.append(
            f"Admissible configurations: {_n(_g(sel, 'n_admissible'))} of {_n(_g(sel, 'grid_size'))} (rule: {sel.get('admissibility_rule', NOT_RUN)}). "
            + ("Not admissible: " + "; ".join(na) + "." if na else "All configurations were admissible.")
        )
        diag.append(
            f"Reference acceptance at τ5 spans {_pct(_g(sel, 'min_ref_accept_tau5'), 2)}–{_pct(_g(sel, 'max_ref_accept_tau5'), 2)} across the {_n(_g(sel, 'grid_size'))} configurations "
            f"(spread {100 * float(_g(sel, 'ref_accept_spread_tau5', float('nan'))):.2f} pp); among the admissible configurations the best is {_pct(_g(sel, 'min_ref_accept_tau5'), 2)} and "
            f"{_n(_g(sel, 'n_configs_tied_with_best'))} of them are within {tol_pp:.1f} pp of it."
        )
        diag.append(
            f"Uniform-box acceptance at τ5 (diagnostic, not used): {_pct(ud2.get('min_tau5'), 3)}–{_pct(ud2.get('max_tau5'), 3)}; "
            f"{_n(ud2.get('n_configs_zero_tau5'))} configuration(s) at exactly 0%."
        )
    if stopped:
        diag.append(f"**SELECTION STOPPED ({stopped.get('reason')}):** {stopped['message']}.")
    if diag:
        p += ["", "## Selection diagnostics", ""] + [f"- {d}" for d in diag]
    cvd = _g(feat, "cv_diagnostics_train")
    if cvd:
        p += ["", "## Coefficient-of-variation features (train split)", "", "| feature | min | median | max |", "|---|---|---|---|"]
        p += [f"| `{k}` | {v['min']:.4g} | {v['median']:.4g} | {v['max']:.4g} |" for k, v in cvd.items()]
    out = Path(path) if path else settings.out_dir / "METHODS.md"
    out.write_text("\n".join(p) + "\n", encoding="utf-8")
    return out
