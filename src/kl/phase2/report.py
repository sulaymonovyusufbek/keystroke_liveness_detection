def _row(df: pd.DataFrame, detector: str, trained_on: str, tested_on: str) -> pd.Series:
    m = df[(df["detector"] == detector) & (df["trained_on"] == trained_on) & (df["tested_on"] == tested_on)]
    return m.iloc[0]


def write_results_md(st: Settings, p2: Mapping[str, Any], out: Path) -> None:
    """RESULTS_PHASE2.md: tables and a paper-style paragraph built from the experiment CSVs."""
    open_set = pd.read_csv(out / "open_set_table.csv")
    matrix = pd.read_csv(out / "attack_matrix.csv")
    loao = pd.read_csv(out / "loao_table.csv")
    realism = pd.read_csv(out / "realism_report.csv")
    meta = read_json(out / "experiments_meta.json", {}) or {}
    gen = read_json(out / "generation_report.json", {}) or {}
    tests = p2["experiments"]["test_attackers"]
    train_atk = p2["experiments"]["train_attackers"]
    n_h, n_u = meta.get("n_test_human_sessions"), meta.get("n_test_users")
    d1 = {a: _row(open_set, "D1", "attack-free", a) for a in tests}
    d2 = {a: _row(open_set, "D2", "attack-free", a) for a in tests}
    hd1, hd2 = d1[tests[0]], d2[tests[0]]
    non5a = [a for a in tests if a != "A5a"]
    worst1 = max(non5a, key=lambda a: d1[a]["apcer_fpr_tau10"])
    worst2 = max(non5a, key=lambda a: d2[a]["apcer_fpr_tau10"])
    best1 = min(non5a, key=lambda a: d1[a]["apcer_fpr_tau10"])
    lines = ["# Phase 2 results", "",
             f"_Run mode: **{'quick' if st.quick else 'full'}**, seed {st.seed}, Phase 1 config hash `{st.config_hash}` (frozen). Attackers were fixed before any detector was run. "
             "APCER = FPR = attacks accepted; BPCER = FNR = humans rejected; a session is accepted iff score ≥ τ. "
             "95% CIs: bootstrap over test users (1,000 resamples, the same resamples in every cell)._", "",
             "## Paper-style summary", ""]
    lines.append(
        f"We evaluated three detectors on the held-out test split ({n_h:,} human sessions from {n_u:,} users) against six non-adaptive attackers whose parameters were fitted only on "
        f"disjoint attacker-pool users. The frozen one-class SVM (D1) rejected {100 * hd1['bpcer_fnr_tau5']:.1f}% of humans at τ5 and {100 * hd1['bpcer_fnr_tau10']:.1f}% at τ10 (BPCER/FNR); "
        f"the Isolation Forest (D2), thresholded on validation humans in the same way, {100 * hd2['bpcer_fnr_tau5']:.1f}% and {100 * hd2['bpcer_fnr_tau10']:.1f}%. "
        f"At τ10 the attack accepted most often by D1 among A1–A5b was {worst1} (APCER/FPR {100 * d1[worst1]['apcer_fpr_tau10']:.1f}%, AUC {d1[worst1]['auc']:.3f}) and the least often {best1} "
        f"({100 * d1[best1]['apcer_fpr_tau10']:.1f}%, AUC {d1[best1]['auc']:.3f}); for D2 the most accepted was {worst2} ({100 * d2[worst2]['apcer_fpr_tau10']:.1f}%, AUC {d2[worst2]['auc']:.3f}). "
        f"The verbatim replay A5a, a genuine human recording, was accepted at τ10 by D1 in {100 * d1['A5a']['apcer_fpr_tau10']:.1f}% and by D2 in {100 * d2['A5a']['apcer_fpr_tau10']:.1f}% of cases "
        f"(AUC {d1['A5a']['auc']:.3f} and {d2['A5a']['auc']:.3f}), as expected: session-level behavioural liveness cannot separate a fresh human session from a recorded one, which motivates challenge sentences "
        "and freshness checks rather than a better classifier.")
    lines.append("")
    d3_rows = matrix[matrix["detector"] == "D3"]
    diag, off = [], []
    for a in train_atk:
        for t in non5a:
            r = _row(matrix, "D3", a, t)
            (diag if a == t else off).append(r["apcer_fpr_tau10"])
    if diag and off:
        lo = loao["detector"].eq("D3")
        loao_apcer = loao.loc[lo, "apcer_fpr_tau10"].to_numpy()
        lines.append(
            f"A supervised Random Forest (D3) trained on one attacker accepted, at τ10, on average {100 * np.mean(diag):.1f}% of attacks from the attacker it was trained on but {100 * np.mean(off):.1f}% of the other "
            f"attackers A1–A4/A5b (cross-attack matrix); when the tested attacker was left out of training entirely (leave-one-attack-out), the mean APCER/FPR at τ10 was {100 * loao_apcer.mean():.1f}% "
            f"(range {100 * loao_apcer.min():.1f}–{100 * loao_apcer.max():.1f}%).")
        lines.append("")
    kmean = realism.groupby("attacker")["ks"].mean().to_dict()
    roll = realism[realism["feature"] == "rollover_rate"].set_index("attacker")
    lines.append(
        "Attacker realism against held-out attacker-pool sessions (mean Kolmogorov–Smirnov statistic over the 23 features; lower = closer): "
        + ", ".join(f"{a} {kmean[a]:.3f}" for a in kmean) + ". Rollover rate (bot vs pool mean): "
        + ", ".join(f"{a} {roll.loc[a, 'bot_mean']:.3f} vs {roll.loc[a, 'pool_mean']:.3f}" for a in roll.index if a in ("A2", "A3", "A4", "A5b")) + ". "
        "The realism report documents attacker strength only and was not used to tune any attacker.")
    lines += ["", "## E1 — open-set table (test split; D1 frozen OCSVM, D2 Isolation Forest; both attack-free)", "",
              "| detector | attacker | " + " | ".join(HEADERS[m] for m in ("apcer_fpr_tau5", "apcer_fpr_tau10", "bpcer_fnr_tau5", "bpcer_fnr_tau10", "auc")) + " |",
              "|---|---|---|---|---|---|---|"]
    for det in ("D1", "D2"):
        for a in tests:
            r = _row(open_set, det, "attack-free", a)
            lines.append(f"| {det} | {a} | " + " | ".join(fmt_cell(r, m) for m in ("apcer_fpr_tau5", "apcer_fpr_tau10", "bpcer_fnr_tau5", "bpcer_fnr_tau10", "auc")) + " |")
    for title, metric in (("APCER/FPR @τ10", "apcer_fpr_tau10"), ("ROC-AUC", "auc")):
        lines += ["", f"## E2 — cross-attack matrix: {title} (rows = detector / training attack, columns = tested attack)", "",
                  "| trained on | " + " | ".join(tests) + " |", "|---|" + "---|" * len(tests)]
        rows = [("D1", "attack-free"), ("D2", "attack-free")] + [("D3", a) for a in train_atk]
        for det, tr in rows:
            lines.append(f"| {det} ← {tr} | " + " | ".join(fmt_cell(_row(matrix, det, tr, t), metric) for t in tests) + " |")
    lines += ["", "## E3 — leave-one-attack-out (D3 trained on all training attackers except the tested one)", "",
              "| tested attacker (held out) | detector | " + " | ".join(HEADERS[m] for m in ("apcer_fpr_tau5", "apcer_fpr_tau10", "bpcer_fnr_tau5", "bpcer_fnr_tau10", "auc")) + " |", "|---|---|---|---|---|---|---|"]
    for _, r in loao.iterrows():
        lines.append(f"| {r['tested_on']} | {r['detector']} ({r['trained_on']}) | " + " | ".join(fmt_cell(r, m) for m in ("apcer_fpr_tau5", "apcer_fpr_tau10", "bpcer_fnr_tau5", "bpcer_fnr_tau10", "auc")) + " |")
    lines += ["", "## Attacker realism (mean KS statistic over features; full table in realism_report.csv)", "", "| attacker | mean KS | max KS (feature) |", "|---|---|---|"]
    for a, g in realism.groupby("attacker"):
        top = g.loc[g["ks"].idxmax()]
        lines.append(f"| {a} | {g['ks'].mean():.3f} | {top['ks']:.3f} (`{top['feature']}`) |")
    if gen:
        lines += ["", "## Generation counts", "", "| attacker | split | bots kept | dropped (non-finite) |", "|---|---|---|---|"]
        for k, v in gen.items():
            lines.append(f"| {v['attacker']} | {v['split']} | {v['n_kept']:,} | {v['n_dropped']:,} |")
    (out / "RESULTS_PHASE2.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
