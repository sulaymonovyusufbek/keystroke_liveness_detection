def _qtable(title_rows: Mapping[str, Mapping[str, float]], unit: str = "") -> list[str]:
    lines = ["| distribution | n | mean | std | q05 | q25 | median | q75 | q95 |", "|---|---|---|---|---|---|---|---|---|"]
    for name, d in title_rows.items():
        if d.get("n", 0) == 0:
            lines.append(f"| {name} | 0 | | | | | | | |")
            continue
        lines.append(f"| {name} | {d['n']:,} | " + " | ".join(f"{d[k]:.4g}" for k in ("mean", "std", "q05", "q25", "median", "q75", "q95")) + " |")
    return lines + [""]


